TEST_F(DatastoreTest, DiseaseRelativeRiskToDisease) {
    IssueReport report;
    const auto asthma = store_->disease_info(Identifier{"asthma"}, report);
    const auto diabetes = store_->disease_info(Identifier{"diabetes"}, report);
    ASSERT_TRUE(asthma.has_value());
    ASSERT_TRUE(diabetes.has_value());

    const auto other = store_->relative_risk_to_disease(*diabetes, *asthma, report);
    ASSERT_TRUE(other.has_value()) << report.to_string();
    EXPECT_EQ(3U, other->columns.size());
    EXPECT_FALSE(other->rows.empty());

    // A disease has no relative risk table against itself.
    IssueReport self_report;
    EXPECT_FALSE(store_->relative_risk_to_disease(*diabetes, *diabetes, self_report).has_value());
    EXPECT_FALSE(self_report.has_errors()) << "an absent interaction is a warning, not an error";
    EXPECT_TRUE(self_report.contains(IssueCode::data_missing_file));
}

