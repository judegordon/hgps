TEST_F(DatastoreTest, RetrieveDiseaseDefinition) {
    for (const auto &item : store_->diseases()) {
        IssueReport report;
        const auto entity = store_->disease(item, country_, report);
        ASSERT_TRUE(entity.has_value()) << item.code.to_string() << ": " << report.to_string();

        EXPECT_FALSE(entity->empty());
        EXPECT_EQ(4U, entity->measures.size());
        EXPECT_EQ(item.code, entity->info.code);
        EXPECT_EQ(country_.code, entity->country.code);

        // Two sexes over 50 ages.
        EXPECT_EQ(100U, entity->items.size());

        // Ordered by (age, gender), because a std::map builds it — the baseline used an
        // unordered_map here, making the item order depend on the standard library.
        EXPECT_TRUE(std::is_sorted(entity->items.begin(), entity->items.end(),
                                   [](const auto &left, const auto &right) {
                                       return std::tie(left.with_age, left.gender) <
                                              std::tie(right.with_age, right.gender);
                                   }));
    }
}

