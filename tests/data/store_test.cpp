TEST_F(DatastoreTest, CountryPopulation) {
    IssueReport report;
    const auto all = store_->population(country_, all_years(), report);
    ASSERT_TRUE(all.has_value()) << report.to_string();
    ASSERT_FALSE(all->empty());

    const auto first_year = all->front().at_time;
    const auto last_year = all->back().at_time;
    const auto mid_year = std::midpoint(first_year, last_year);

    const auto filtered = store_->population(
        country_,
        [mid_year](unsigned int year) {
            return year >= static_cast<unsigned int>(mid_year - 1) &&
                   year <= static_cast<unsigned int>(mid_year + 1);
        },
        report);
    ASSERT_TRUE(filtered.has_value());

    EXPECT_GT(all->size(), filtered->size());
    EXPECT_LT(first_year, filtered->front().at_time);
    EXPECT_GT(last_year, filtered->back().at_time);

    // Every (year, age) is present exactly once, with both sexes positive, and the series is
    // ordered by (year, age) — which the analysis and demographic modules rely on.
    std::map<int, std::map<int, hgps::core::PopulationItem>> table;
    for (const auto &item : *all) {
        EXPECT_TRUE(table[item.at_time].emplace(item.with_age, item).second)
            << "duplicate row for year " << item.at_time << " age " << item.with_age;
    }

    for (int year = first_year; year <= last_year; ++year) {
        ASSERT_TRUE(table.contains(year)) << year;
        for (int age = 0; age <= 49; ++age) {
            ASSERT_TRUE(table.at(year).contains(age)) << year << " " << age;
            const auto &item = table.at(year).at(age);
            EXPECT_GT(item.males, 0.0F);
            EXPECT_GT(item.females, 0.0F);
            EXPECT_NEAR(item.total, item.males + item.females, 0.01F);
        }
    }

    EXPECT_TRUE(std::is_sorted(all->begin(), all->end()));
}

