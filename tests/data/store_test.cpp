TEST_F(DatastoreTest, DiseaseRelativeRiskToRiskFactor) {
    IssueReport report;
    const auto diabetes = store_->disease_info(Identifier{"diabetes"}, report);
    ASSERT_TRUE(diabetes.has_value());

    for (const auto gender : {Gender::male, Gender::female}) {
        const auto table =
            store_->relative_risk_to_risk_factor(*diabetes, gender, Identifier{"bmi"}, report);
        ASSERT_TRUE(table.has_value()) << report.to_string();

        // Age plus five value bands.
        EXPECT_EQ(6U, table->columns.size());
        EXPECT_FALSE(table->rows.empty());
        EXPECT_NE(table->rows[0][1], table->rows[0][2]);
    }

    // A factor with no table is a warning and a disabled effect, not a failure.
    IssueReport missing;
    EXPECT_FALSE(
        store_->relative_risk_to_risk_factor(*diabetes, Gender::male, Identifier{"sodium"}, missing)
            .has_value());
    EXPECT_FALSE(missing.has_errors());
    EXPECT_EQ(1U, missing.warning_count());
}

