    void SetUp() override {
        const auto pack = hgps::test::synthetic_data_dir();

        // Fail, do not skip. The baseline skips 35 tests when its fixture is absent and a green
        // run then proves less than it appears to (audit B-11); this pack is generated by the
        // build, so its absence is a broken build.
        ASSERT_TRUE(std::filesystem::is_directory(pack))
            << "the synthetic data pack is missing from " << pack.string()
            << "; it is generated by the build target hgps_fixtures";

        store_ = Store::open(pack, report_);
        ASSERT_TRUE(store_.has_value()) << report_.to_string();
        ASSERT_FALSE(report_.has_errors()) << report_.to_string();

        const auto found = store_->country("SYN", report_);
        ASSERT_TRUE(found.has_value()) << report_.to_string();
        country_ = *found;
    }

    static Store::TimeFilter all_years() {
        return [](unsigned int) { return true; };
    }

    IssueReport report_;
    std::optional<Store> store_;
