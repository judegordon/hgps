TEST_F(DatastoreTest, RetrieveLmsParameters) {
    IssueReport report;
    const auto lms = store_->lms_parameters(report);
    ASSERT_TRUE(lms.has_value()) << report.to_string();
    ASSERT_FALSE(lms->empty());

    const auto males =
        std::count_if(lms->begin(), lms->end(), [](const auto &row) {
            return row.gender == Gender::male;
        });
    const auto females =
        std::count_if(lms->begin(), lms->end(), [](const auto &row) {
            return row.gender == Gender::female;
        });

    EXPECT_GT(males, 0);
    EXPECT_EQ(males, females);
    EXPECT_EQ(lms->size(), static_cast<std::size_t>(males + females));

    for (const auto &row : *lms) {
        EXPECT_GT(row.mu, 0.0);
        EXPECT_GT(row.sigma, 0.0);
    }
}
